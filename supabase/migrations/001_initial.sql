-- Single-workspace MVP. No automatic membership on sign-up.
begin;
create table public.members (user_id uuid primary key references auth.users(id) on delete cascade, role text not null check(role in ('requester','engineer','admin')));
create table public.teams (id uuid primary key default gen_random_uuid(), name text not null, categories text[] not null, skills text[] not null, capacity integer not null check(capacity>0));
create table public.tickets (
 id uuid primary key default gen_random_uuid(), number bigint generated by default as identity unique,
 title text not null check(length(title) between 5 and 160), description text not null check(length(description) between 20 and 5000),
 category text not null check(category in ('Network','Identity','Applications','Hardware','Cloud','Security')),
 priority text not null check(priority in ('P1','P2','P3','P4')), status text not null default 'open' check(status in ('open','in_progress','waiting','resolved')),
 reporter_id uuid references auth.users(id), assigned_team_id uuid references public.teams(id),
 created_at timestamptz not null default now(), sla_due_at timestamptz not null, resolved_at timestamptz,
 solution text not null default '', version integer not null default 1, is_sample boolean not null default false,
 check((status='resolved' and resolved_at is not null and length(trim(solution))>=10) or (status<>'resolved' and resolved_at is null)), check(sla_due_at>created_at));
create table public.recommendations (
 id uuid primary key default gen_random_uuid(), ticket_id uuid not null references public.tickets(id), ticket_version integer not null,
 analysis jsonb not null, sources jsonb not null, resolver jsonb not null, model text not null,
 status text not null default 'pending' check(status in ('pending','approved','rejected','superseded')),
 created_at timestamptz not null default now(), created_by uuid references auth.users(id));
create table public.decisions (id uuid primary key default gen_random_uuid(), recommendation_id uuid not null unique references public.recommendations(id), actor_id uuid not null references auth.users(id), decision text not null check(decision in ('approved','rejected')), comment text not null check(length(trim(comment)) between 5 and 2000), created_at timestamptz not null default now());
create table public.ticket_history (id uuid primary key default gen_random_uuid(), ticket_id uuid not null references public.tickets(id), actor_id uuid references auth.users(id), event text not null, details jsonb not null default '{}', created_at timestamptz not null default now());
create index on public.tickets(status,created_at desc);
create index on public.recommendations(ticket_id,created_at desc);
create index on public.ticket_history(ticket_id,created_at desc);
create function public.workspace_role() returns text language sql stable security definer set search_path=public as $$ select role from members where user_id=auth.uid() $$;
create function public.can_read_ticket(tid uuid) returns boolean language sql stable security definer set search_path=public as $$ select exists(select 1 from tickets where id=tid and (public.workspace_role() in ('engineer','admin') or (public.workspace_role()='requester' and reporter_id=auth.uid()))) $$;
alter table public.members enable row level security;
alter table public.teams enable row level security;
alter table public.tickets enable row level security;
alter table public.recommendations enable row level security;
alter table public.decisions enable row level security;
alter table public.ticket_history enable row level security;
create policy member_self on public.members for select to authenticated using(user_id=auth.uid());
create policy team_read on public.teams for select to authenticated using(public.workspace_role() is not null);
create policy ticket_read on public.tickets for select to authenticated using(public.workspace_role() in ('engineer','admin') or (public.workspace_role()='requester' and reporter_id=auth.uid()));
create policy recommendation_read on public.recommendations for select to authenticated using(public.workspace_role() in ('engineer','admin'));
create policy decision_read on public.decisions for select to authenticated using(public.workspace_role() in ('engineer','admin'));
create policy history_read on public.ticket_history for select to authenticated using(public.can_read_ticket(ticket_id));
revoke all on public.members,public.teams,public.tickets,public.recommendations,public.decisions,public.ticket_history from anon,authenticated;
grant select on public.members,public.teams,public.tickets,public.recommendations,public.decisions,public.ticket_history to authenticated;
grant all on public.members,public.teams,public.tickets,public.recommendations,public.decisions,public.ticket_history to service_role;
grant usage,select on all sequences in schema public to service_role;

create function public.create_ticket(p_data jsonb) returns public.tickets language plpgsql security definer set search_path=public as $$
declare t tickets; budget integer;
begin
 if workspace_role() is null then raise exception 'Workspace membership required' using errcode='42501'; end if;
 budget:=case p_data->>'priority' when 'P1' then 4 when 'P2' then 8 when 'P3' then 24 when 'P4' then 72 else null end;
 insert into tickets(title,description,category,priority,reporter_id,sla_due_at) values(trim(p_data->>'title'),trim(p_data->>'description'),p_data->>'category',p_data->>'priority',auth.uid(),now()+make_interval(hours=>budget)) returning * into t;
 insert into ticket_history(ticket_id,actor_id,event,details) values(t.id,auth.uid(),'created',jsonb_build_object('priority',t.priority));
 return t;
end $$;

create function public.change_ticket(p_id uuid,p_data jsonb) returns public.tickets language plpgsql security definer set search_path=public as $$
declare t tickets;
begin
 if coalesce(workspace_role(),'') not in ('engineer','admin') then raise exception 'Engineer required' using errcode='42501'; end if;
 select * into t from tickets where id=p_id for update;
 if not found then raise exception 'Ticket missing'; end if;
 if t.version is distinct from (p_data->>'version')::int then raise exception 'Ticket changed; refresh' using errcode='40001'; end if;
 if length(trim(coalesce(p_data->>'note',''))) not between 5 and 2000 then raise exception 'Review note required'; end if;
 update tickets set status=p_data->>'status',solution=case when p_data->>'status'='resolved' then trim(p_data->>'solution') else '' end, resolved_at=case when p_data->>'status'='resolved' then coalesce(resolved_at,now()) else null end, version=version+1 where id=p_id returning * into t;
 update recommendations set status='superseded' where ticket_id=p_id and status='pending';
 insert into ticket_history(ticket_id,actor_id,event,details) values(p_id,auth.uid(),'status_changed',p_data);
 return t;
end $$;

create function public.add_note(p_id uuid,p_note text) returns void language plpgsql security definer set search_path=public as $$
begin
 if not can_read_ticket(p_id) then raise exception 'Access denied' using errcode='42501'; end if;
 if length(trim(coalesce(p_note,''))) not between 3 and 2000 then raise exception 'Invalid note'; end if;
 insert into ticket_history(ticket_id,actor_id,event,details) values(p_id,auth.uid(),'note',jsonb_build_object('note',p_note));
end $$;

-- Only backend service-role calls this after checking the authenticated engineer.
create function public.save_recommendation(p_data jsonb,p_actor uuid) returns public.recommendations language plpgsql security definer set search_path=public as $$
declare t tickets; r recommendations;
begin
 if not exists(select 1 from members where user_id=p_actor and role in ('engineer','admin')) then raise exception 'Engineer required' using errcode='42501'; end if;
 select * into t from tickets where id=(p_data->>'ticket_id')::uuid for update;
 if not found or t.status='resolved' or t.version is distinct from (p_data->>'ticket_version')::int then raise exception 'Ticket changed; refresh' using errcode='40001'; end if;
 update recommendations set status='superseded' where ticket_id=t.id and status='pending';
 insert into recommendations(ticket_id,ticket_version,analysis,sources,resolver,model,created_by) values(t.id,t.version,p_data->'analysis',p_data->'sources',p_data->'resolver',p_data->>'model',p_actor) returning * into r;
 insert into ticket_history(ticket_id,actor_id,event,details) values(t.id,p_actor,'analysis_generated',jsonb_build_object('recommendation_id',r.id,'model',r.model));
 return r;
end $$;

create function public.review_recommendation(p_id uuid,p_decision text,p_comment text) returns public.recommendations language plpgsql security definer set search_path=public as $$
declare r recommendations; t tickets; tid uuid;
begin
 if coalesce(workspace_role(),'') not in ('engineer','admin') then raise exception 'Engineer required' using errcode='42501'; end if;
 if p_decision not in ('approved','rejected') then raise exception 'Invalid decision'; end if;
 select ticket_id into tid from recommendations where id=p_id;
 -- Same lock order as save/change: ticket, then recommendation.
 select * into t from tickets where id=tid for update;
 select * into r from recommendations where id=p_id for update;
 if not found then raise exception 'Recommendation missing'; end if;
 if r.status<>'pending' or t.version<>r.ticket_version or t.status='resolved' then raise exception 'Stale or already reviewed recommendation' using errcode='40001'; end if;
 insert into decisions(recommendation_id,actor_id,decision,comment) values(p_id,auth.uid(),p_decision,trim(p_comment));
 update recommendations set status=p_decision where id=p_id returning * into r;
 if p_decision='approved' then
  update tickets set assigned_team_id=(r.resolver->>'id')::uuid, category=r.analysis->>'category', version=version+1 where id=t.id;
  -- Priority/SLA remain unchanged. Approval never runs remediation or closes tickets.
 end if;
 insert into ticket_history(ticket_id,actor_id,event,details) values(t.id,auth.uid(),'recommendation_'||p_decision,jsonb_build_object('recommendation_id',p_id,'comment',p_comment,'applied',p_decision='approved'));
 return r;
end $$;
revoke execute on function public.workspace_role(),public.can_read_ticket(uuid),public.create_ticket(jsonb),public.change_ticket(uuid,jsonb),public.add_note(uuid,text),public.save_recommendation(jsonb,uuid),public.review_recommendation(uuid,text,text) from public,anon,authenticated;
grant execute on function public.workspace_role(),public.can_read_ticket(uuid),public.create_ticket(jsonb),public.change_ticket(uuid,jsonb),public.add_note(uuid,text),public.review_recommendation(uuid,text,text) to authenticated;
grant execute on function public.save_recommendation(jsonb,uuid) to service_role;
commit;
